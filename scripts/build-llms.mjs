// Generates llms-full.txt from the README and the compiled type declarations,
// so the AI-facing reference always matches the published API.
import { readFileSync, writeFileSync } from "node:fs";

const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), "utf8");
const { version } = JSON.parse(read("package.json"));
const readme = read("README.md")
  .replace(/^\[!\[.*$\n?/gm, "") // badges
  .replace(/<a id="[^"]*"><\/a>\n\n/g, "")
  .trim();
const declarations = ["dist/PolaroidCarousel.d.ts", "dist/use-carousel.d.ts", "dist/math.d.ts"]
  .map((file) => `### ${file.replace("dist/", "")}\n\n\`\`\`ts\n${read(file).trim()}\n\`\`\``)
  .join("\n\n");

writeFileSync(
  new URL("../llms-full.txt", import.meta.url),
  `<!-- Generated by scripts/build-llms.mjs for react-polaroid-carousel@${version}. Do not edit by hand. -->

${readme}

## Type definitions (react-polaroid-carousel@${version})

Everything below is exported from "react-polaroid-carousel".

${declarations}
`,
);
console.log("wrote llms-full.txt");
